import 'package:flutter/material.dart';
import '../../../../core/constants/app_constants.dart';
import '../../../../core/widgets/widgets.dart';
import '../../../../simulation/simulation.dart';
import '../../../../theme/app_colors.dart';
import '../../analysis/presentation/widgets/lab_chart_widget.dart';

enum ExperimentType {
  lineRegulation,
  loadRegulation,
}

/// Guided Virtual Laboratory Experiment Workspace for Line and Load Regulation
class ExperimentScreen extends StatefulWidget {
  const ExperimentScreen({super.key});

  @override
  State<ExperimentScreen> createState() => _ExperimentScreenState();
}

class _ExperimentScreenState extends State<ExperimentScreen> {
  final SimulatorController _controller = SimulatorController.instance;

  ExperimentType _selectedExperiment = ExperimentType.lineRegulation;
  List<ZenerSimulationResult> _recordedReadings = [];
  bool _isAutoGenerated = false;

  // Sweep Config Parameters
  final double _vinStart = 0.0;
  final double _vinStop = 20.0;
  final double _vinStep = 1.0;

  final double _rlStart = 100.0;
  final double _rlStop = 3000.0;
  final double _rlStep = 200.0;

  @override
  void initState() {
    super.initState();
    _controller.addListener(_onControllerUpdated);
  }

  @override
  void dispose() {
    _controller.removeListener(_onControllerUpdated);
    super.dispose();
  }

  void _onControllerUpdated() {
    setState(() {});
  }

  void _generateExperimentData() {
    final params = _controller.parameters;
    final List<ZenerSimulationResult> results = [];

    if (_selectedExperiment == ExperimentType.lineRegulation) {
      double currentVin = _vinStart;
      while (currentVin <= _vinStop + 0.001) {
        final p = params.copyWith(vin: currentVin);
        results.add(_controller.simulator.simulate(p));
        currentVin += _vinStep;
      }
    } else {
      double currentRl = _rlStart;
      while (currentRl <= _rlStop + 0.001) {
        final p = params.copyWith(rl: currentRl);
        results.add(_controller.simulator.simulate(p));
        currentRl += _rlStep;
      }
    }

    setState(() {
      _recordedReadings = results;
      _isAutoGenerated = true;
    });
  }

  void _recordSinglePoint() {
    setState(() {
      _recordedReadings.add(_controller.currentResult);
      _isAutoGenerated = false;
    });
  }

  void _clearReadings() {
    setState(() {
      _recordedReadings.clear();
      _isAutoGenerated = false;
    });
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final params = _controller.parameters;

    return SingleChildScrollView(
      padding: const EdgeInsets.all(AppConstants.spaceLg),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Section Header
          SectionHeader(
            title: 'Virtual Electronics Laboratory Bench',
            subtitle: 'Formal curriculum laboratory procedures with automated observation tables and regulation factors',
            icon: Icons.science_rounded,
            trailing: StatusIndicator(
              label: '${_recordedReadings.length} Readings Logged',
              type: _recordedReadings.isNotEmpty ? StatusType.active : StatusType.inactive,
            ),
          ),

          // Experiment Mode Selector
          Row(
            children: [
              Expanded(
                child: ChoiceChip(
                  label: const Padding(
                    padding: EdgeInsets.symmetric(vertical: 4),
                    child: Text('Experiment 1: Line Regulation (ΔVout / ΔVin)'),
                  ),
                  selected: _selectedExperiment == ExperimentType.lineRegulation,
                  onSelected: (val) {
                    if (val) {
                      setState(() {
                        _selectedExperiment = ExperimentType.lineRegulation;
                        _recordedReadings.clear();
                      });
                    }
                  },
                ),
              ),
              const SizedBox(width: AppConstants.spaceMd),
              Expanded(
                child: ChoiceChip(
                  label: const Padding(
                    padding: EdgeInsets.symmetric(vertical: 4),
                    child: Text('Experiment 2: Load Regulation (VNL - VFL) / VFL'),
                  ),
                  selected: _selectedExperiment == ExperimentType.loadRegulation,
                  onSelected: (val) {
                    if (val) {
                      setState(() {
                        _selectedExperiment = ExperimentType.loadRegulation;
                        _recordedReadings.clear();
                      });
                    }
                  },
                ),
              ),
            ],
          ),
          const SizedBox(height: AppConstants.spaceLg),

          // Lab Procedure Manual & Apparatus Card
          AppCard(
            padding: const EdgeInsets.all(AppConstants.spaceLg),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    Icon(Icons.description_outlined, color: theme.colorScheme.primary),
                    const SizedBox(width: AppConstants.spaceSm),
                    Text(
                      _selectedExperiment == ExperimentType.lineRegulation
                          ? 'Aim: Study of Line Regulation of Zener Diode'
                          : 'Aim: Study of Load Regulation of Zener Diode',
                      style: theme.textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: AppConstants.spaceSm),
                Text(
                  _selectedExperiment == ExperimentType.lineRegulation
                      ? 'Procedure: Keep load resistor RL (${params.rl.toStringAsFixed(0)}Ω), series resistor Rs (${params.rs.toStringAsFixed(0)}Ω), and Vz (${params.vz}V) fixed. Vary input DC voltage Vin in incremental steps from $_vinStart V to $_vinStop V. Measure Vout, Is, and Iz.'
                      : 'Procedure: Keep input DC voltage Vin (${params.vin.toStringAsFixed(1)}V), series resistor Rs (${params.rs.toStringAsFixed(0)}Ω), and Vz (${params.vz}V) fixed. Vary load resistor RL from $_rlStart Ω to $_rlStop Ω in steps of $_rlStep Ω. Record Vout, load current IL, and Zener current Iz.',
                  style: theme.textTheme.bodyMedium?.copyWith(
                    color: theme.colorScheme.onSurfaceVariant,
                  ),
                ),
                const SizedBox(height: AppConstants.spaceMd),
                const Divider(),
                const SizedBox(height: AppConstants.spaceSm),

                // Controls row
                Wrap(
                  spacing: AppConstants.spaceSm,
                  runSpacing: AppConstants.spaceSm,
                  children: [
                    AppButton.primary(
                      label: 'Generate Full Run Data',
                      icon: Icons.play_arrow_rounded,
                      onPressed: _generateExperimentData,
                    ),
                    AppButton.secondary(
                      label: 'Log Current Operating Point',
                      icon: Icons.add_circle_outline_rounded,
                      onPressed: _recordSinglePoint,
                    ),
                    AppButton.secondary(
                      label: 'Clear Observations',
                      icon: Icons.delete_outline_rounded,
                      onPressed: _clearReadings,
                    ),
                  ],
                ),
              ],
            ),
          ),
          const SizedBox(height: AppConstants.spaceXl),

          // Observation Table
          SectionHeader(
            title: 'Laboratory Observation Table',
            subtitle: 'Logged trial recordings with precision SI unit formatting',
            icon: Icons.table_chart_outlined,
            trailing: _recordedReadings.isNotEmpty
                ? Chip(
                    label: Text(_isAutoGenerated ? 'Auto-Sweep Log' : 'Manual Point Log'),
                    backgroundColor: theme.colorScheme.primaryContainer,
                  )
                : null,
          ),

          if (_recordedReadings.isEmpty)
            const EmptyStateWidget(
              icon: Icons.science_outlined,
              title: 'No Observation Data Logged',
              description: 'Click "Generate Full Run Data" or "Log Current Operating Point" above to populate the observation table.',
            )
          else ...[
            AppCard(
              padding: EdgeInsets.zero,
              child: SingleChildScrollView(
                scrollDirection: Axis.horizontal,
                child: DataTable(
                  headingRowColor: WidgetStateProperty.all(
                    theme.colorScheme.surfaceContainerHigh,
                  ),
                  columns: const [
                    DataColumn(label: Text('Trial #', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('Vin (V)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('RL (Ω)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('Vout (V)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('Is (mA)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('IL (mA)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('Iz (mA)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('Pz (mW)', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('State', style: TextStyle(fontWeight: FontWeight.bold))),
                  ],
                  rows: _recordedReadings.asMap().entries.map((entry) {
                    final index = entry.key + 1;
                    final row = entry.value;
                    return DataRow(
                      cells: [
                        DataCell(Text('$index', style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(Text(row.vin.toStringAsFixed(2), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(Text(row.rl.toStringAsFixed(0), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(
                          Text(
                            row.vout.toStringAsFixed(3),
                            style: TextStyle(
                              fontFamily: 'monospace',
                              fontWeight: FontWeight.bold,
                              color: row.isRegulating ? AppColors.voltageOut : null,
                            ),
                          ),
                        ),
                        DataCell(Text(row.seriesCurrentMilliAmps.toStringAsFixed(2), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(Text(row.loadCurrentMilliAmps.toStringAsFixed(2), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(Text(row.zenerCurrentMilliAmps.toStringAsFixed(2), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(Text(row.zenerPowerMilliWatts.toStringAsFixed(1), style: const TextStyle(fontFamily: 'monospace'))),
                        DataCell(
                          StatusIndicator(
                            label: row.zenerState.displayName,
                            type: row.isRegulating
                                ? StatusType.active
                                : (row.isBelowBreakdown ? StatusType.inactive : StatusType.warning),
                            showDot: false,
                          ),
                        ),
                      ],
                    );
                  }).toList(),
                ),
              ),
            ),
            const SizedBox(height: AppConstants.spaceXl),

            // Regulation Calculations Card
            _buildRegulationSummaryCard(theme),
            const SizedBox(height: AppConstants.spaceXl),

            // Experiment Generated Curve
            AppCard(
              padding: const EdgeInsets.all(AppConstants.spaceLg),
              child: _selectedExperiment == ExperimentType.lineRegulation
                  ? LabChartWidget(
                      title: 'Experiment Curve: Line Regulation (Vin vs Vout)',
                      xLabel: 'Input Voltage Vin',
                      yLabel: 'Output Voltage Vout',
                      xUnit: 'V',
                      yUnit: 'V',
                      lineColor: AppColors.voltageOut,
                      points: _recordedReadings.map((r) => GraphPoint(x: r.vin, y: r.vout)).toList(),
                      interpretation:
                          'Result: Output voltage is regulated tightly at ~${params.vz}V across the active breakdown range.',
                    )
                  : LabChartWidget(
                      title: 'Experiment Curve: Load Regulation (RL vs Vout)',
                      xLabel: 'Load Resistance RL',
                      yLabel: 'Output Voltage Vout',
                      xUnit: 'Ω',
                      yUnit: 'V',
                      lineColor: AppColors.primary,
                      points: _recordedReadings.map((r) => GraphPoint(x: r.rl, y: r.vout)).toList(),
                      interpretation:
                          'Result: As load resistance changes from full-load to light-load, output voltage remains stabilized at Vz.',
                    ),
            ),
          ],
        ],
      ),
    );
  }

  Widget _buildRegulationSummaryCard(ThemeData theme) {
    if (_recordedReadings.length < 2) {
      return const SizedBox.shrink();
    }

    final regulatingPoints = _recordedReadings.where((r) => r.isRegulating).toList();

    if (_selectedExperiment == ExperimentType.lineRegulation) {
      if (regulatingPoints.length < 2) {
        return const StateCallout(
          title: 'Line Regulation Analysis',
          message: 'Insufficient points in the regulating region to compute line regulation. Increase Vin sweep range.',
          type: CalloutType.warning,
        );
      }

      final first = regulatingPoints.first;
      final last = regulatingPoints.last;
      final deltaVin = last.vin - first.vin;
      final deltaVout = last.vout - first.vout;
      final avgVout = (first.vout + last.vout) / 2.0;

      // Standard differential line regulation: ΔVout / ΔVin (V/V or mV/V)
      final lineRegFactor = deltaVin != 0 ? (deltaVout / deltaVin) : 0.0;
      final lineRegMilliVoltsPerVolt = lineRegFactor * 1000.0;

      // Fractional percentage line regulation: (ΔVout / Vout_nom) / ΔVin * 100 (%/V)
      final lineRegPercentPerVolt = (deltaVin != 0 && avgVout != 0)
          ? ((deltaVout / avgVout) / deltaVin) * 100.0
          : 0.0;

      return AppCard(
        padding: const EdgeInsets.all(AppConstants.spaceLg),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Line Regulation Calculation & Report',
              style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: AppConstants.spaceSm),
            Text(
              'Standard Definition: Line Regulation = ΔVout / ΔVin = (${last.vout.toStringAsFixed(3)}V - ${first.vout.toStringAsFixed(3)}V) / (${last.vin.toStringAsFixed(1)}V - ${first.vin.toStringAsFixed(1)}V)',
              style: const TextStyle(fontFamily: 'monospace', fontSize: 12),
            ),
            const SizedBox(height: AppConstants.spaceXs),
            Text(
              'Calculated: ${lineRegFactor.toStringAsFixed(4)} V/V  (${lineRegMilliVoltsPerVolt.toStringAsFixed(2)} mV/V)',
              style: TextStyle(
                fontFamily: 'monospace',
                fontSize: 13,
                fontWeight: FontWeight.bold,
                color: theme.colorScheme.primary,
              ),
            ),
            const SizedBox(height: AppConstants.spaceXs),
            Text(
              'Alternative Lab Convention: [(ΔVout / Vout) ÷ ΔVin] × 100% = ${lineRegPercentPerVolt.toStringAsFixed(3)} %/V',
              style: const TextStyle(fontFamily: 'monospace', fontSize: 12),
            ),
            const SizedBox(height: AppConstants.spaceSm),
            const Text(
              'Educational Note: Within the idealized regulating region with dynamic bulk resistance Rz = 0Ω, Vout is strictly clamped at Vz (ΔVout = 0V), yielding 0.000 V/V line regulation. In real hardware, finite dynamic resistance and temperature variations yield non-zero line regulation.',
              style: TextStyle(fontSize: 12, color: Colors.grey),
            ),
          ],
        ),
      );
    } else {
      // Load Regulation
      final fullLoad = _recordedReadings.first; // lowest RL
      final noLoad = _recordedReadings.last; // highest RL
      final vfl = fullLoad.vout;
      final vnl = noLoad.vout;
      final loadRegPercent = vfl != 0 ? ((vnl - vfl) / vfl) * 100.0 : 0.0;

      return AppCard(
        padding: const EdgeInsets.all(AppConstants.spaceLg),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Load Regulation Calculation & Report',
              style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: AppConstants.spaceSm),
            const Text(
              'Load Regulation (%) = (V_NL - V_FL) / V_FL × 100%',
              style: TextStyle(fontFamily: 'monospace', fontSize: 12),
            ),
            const SizedBox(height: AppConstants.spaceXs),
            Text(
              'V_NL (${noLoad.rl.toStringAsFixed(0)}Ω) = ${vnl.toStringAsFixed(3)}V,   V_FL (${fullLoad.rl.toStringAsFixed(0)}Ω) = ${vfl.toStringAsFixed(3)}V',
              style: const TextStyle(fontFamily: 'monospace', fontSize: 12),
            ),
            const SizedBox(height: AppConstants.spaceXs),
            Text(
              'Calculated Load Regulation = ${loadRegPercent.toStringAsFixed(3)}%',
              style: TextStyle(
                fontFamily: 'monospace',
                fontSize: 14,
                fontWeight: FontWeight.bold,
                color: theme.colorScheme.primary,
              ),
            ),
          ],
        ),
      );
    }
  }
}
